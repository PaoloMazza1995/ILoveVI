// Single, repo-wide switch for :core:mapview's bundled dev map image (step 5A-bis): `true`
// unless this build was invoked with `-Pilovevi.release=true`. Baked into a `const val` at
// compile time (see generateMapViewBuildConfig below), never a runtime-togglable setting — see
// the module README's "Release safety" section for why no AGP BuildConfig/buildType plumbing is
// used here (this project has no established per-module Android buildType convention yet).
val isIloveViReleaseBuild =
    (findProperty("ilovevi.release") as String?)?.toBooleanStrictOrNull() ?: false

val mapViewBuildConfigDir = layout.buildDirectory.dir("generated/mapViewBuildConfig")

val generateMapViewBuildConfig by tasks.registering {
    val outputDir = mapViewBuildConfigDir
    val releaseBuild = isIloveViReleaseBuild
    outputs.dir(outputDir)
    doLast {
        val packageDir = outputDir.get().dir("com/pamaz/vi/core/mapview").asFile
        packageDir.mkdirs()
        packageDir.resolve("MapViewBuildConfig.kt").writeText(
            """
            |// Generated by :core:mapview's build.gradle.kts (generateMapViewBuildConfig) — do not edit by hand.
            |package com.pamaz.vi.core.mapview
            |
            |/** See [MapViewBuildConfig.singleImageDevModeEnabled]'s KDoc. */
            |internal const val SINGLE_IMAGE_DEV_MODE_ENABLED: Boolean = ${!releaseBuild}
            |
            """.trimMargin()
        )
    }
}

