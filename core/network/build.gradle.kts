import java.util.Properties

plugins {
    id("kmm-library-plugin")
    alias(libs.plugins.kotlinSerialization)
}

// Supabase project URL + publishable/anon key: build-time config only, never hardcoded in source
// and never committed. Read from a real environment variable first (CI), falling back to the
// git-ignored root `local.properties` (same file `:tools:map-editor`/`:tools:tilegen` already use
// for these two exact keys — see `local.properties`'s `SUPABASE_URL`/`SUPABASE_ANON_KEY` lines).
// Unlike those JVM-only tools (which forward real env vars into their own process at run time),
// this is a KMP library consumed by the Android/iOS app: there is no shell environment on a phone
// to read from, so the values are baked into a generated `const val` at *build* time instead — the
// same `generate<Module>BuildConfig` task shape `:core:mapview` already established for its own
// release-gate flag. A blank value compiles (so a config-less `./gradlew build` still works) but
// fails loudly at runtime via `SupabaseConfig.fromBuildConfig()`'s `require(...)`.
val localProperties = Properties().apply {
    val localPropertiesFile = rootProject.file("local.properties")
    if (localPropertiesFile.exists()) {
        localPropertiesFile.inputStream().use { load(it) }
    }
}

fun supabaseConfigValue(key: String): String =
    (System.getenv(key) ?: localProperties.getProperty(key))?.trim() ?: ""

/** Escapes a value so it can be embedded as a Kotlin string literal in the generated file below. */
fun String.toKotlinStringLiteralContent(): String =
    replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$")

val supabaseUrl = supabaseConfigValue("SUPABASE_URL")
val supabaseAnonKey = supabaseConfigValue("SUPABASE_ANON_KEY")

val networkBuildConfigDir = layout.buildDirectory.dir("generated/networkBuildConfig")

val generateNetworkBuildConfig by tasks.registering {
    val outputDir = networkBuildConfigDir
    val url = supabaseUrl.toKotlinStringLiteralContent()
    val anonKey = supabaseAnonKey.toKotlinStringLiteralContent()
    outputs.dir(outputDir)
    doLast {
        val packageDir = outputDir.get().dir("com/pamaz/vi/core/network/config").asFile
        packageDir.mkdirs()
        packageDir.resolve("NetworkBuildConfig.kt").writeText(
            """
            |// Generated by :core:network's build.gradle.kts (generateNetworkBuildConfig) — do not edit by hand.
            |// Values come from the SUPABASE_URL / SUPABASE_ANON_KEY environment variables, falling back to
            |// the git-ignored root local.properties — never hardcoded, never committed. See SupabaseConfig's KDoc.
            |package com.pamaz.vi.core.network.config
            |
            |internal const val SUPABASE_URL: String = "$url"
            |internal const val SUPABASE_ANON_KEY: String = "$anonKey"
            |
            """.trimMargin()
        )
    }
}

