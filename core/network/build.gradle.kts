import java.util.Properties

plugins {
    id("kmm-library-plugin")
    alias(libs.plugins.kotlinSerialization)
}

// Supabase project URL + publishable/anon key: build-time config only, never hardcoded in source
// and never committed. Read from a real environment variable first (CI), falling back to the
// git-ignored root `local.properties` (same file `:tools:map-editor`/`:tools:tilegen` already use
// for these two exact keys — see `local.properties`'s `SUPABASE_URL`/`SUPABASE_ANON_KEY` lines).
// Unlike those JVM-only tools (which forward real env vars into their own process at run time),
// this is a KMP library consumed by the Android/iOS app: there is no shell environment on a phone
// to read from, so the values are baked into a generated `const val` at *build* time instead — the
// same `generate<Module>BuildConfig` task shape `:core:mapview` already established for its own
// release-gate flag. A blank value compiles (so a config-less `./gradlew build` still works) but
// fails loudly at runtime via `SupabaseConfig.fromBuildConfig()`'s `require(...)`.
val localProperties = Properties().apply {
    val localPropertiesFile = rootProject.file("local.properties")
    if (localPropertiesFile.exists()) {
        localPropertiesFile.inputStream().use { load(it) }
    }
}

fun supabaseConfigValue(key: String): String =
    (System.getenv(key) ?: localProperties.getProperty(key))?.trim() ?: ""

/** Escapes a value so it can be embedded as a Kotlin string literal in the generated file below. */
fun String.toKotlinStringLiteralContent(): String =
    replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$")

val supabaseUrl = supabaseConfigValue("SUPABASE_URL")
val supabaseAnonKey = supabaseConfigValue("SUPABASE_ANON_KEY")

// Google sign-in (step 13B) — see docs/auth-notes.md §6 for exactly how/why these two are read.
// GOOGLE_WEB_CLIENT_ID backs both Android's Credential Manager server client ID and the
// iOS/Android web-OAuth Google provider config. GOOGLE_IOS_CLIENT_ID is read but not used by the
// shipped iOS flow (web OAuth, not native GoogleSignIn-iOS) — it's the extension point §1
// documents for a future native-iOS-Google switch; reading it now, even unused, means that switch
// never needs a new local.properties key.
val googleWebClientId = supabaseConfigValue("GOOGLE_WEB_CLIENT_ID")
val googleIosClientId = supabaseConfigValue("GOOGLE_IOS_CLIENT_ID")

// Whether the Account section (Google/Apple sign-in) renders at all — separate from
// GoogleAuthConfig.isConfigured()/platform checks, which only decide *which* buttons show once the
// section is already visible. Unset/blank/anything other than "true" means off, the safe default:
// a dev's `local.properties` without this key renders Settings exactly as before this flag existed.
// Opt in with `ACCOUNT_LOGIN_ENABLED=true` in the root local.properties to try the Google/Apple
// sign-in flows locally — see docs/auth-notes.md §6.
val accountLoginEnabled =
    supabaseConfigValue("ACCOUNT_LOGIN_ENABLED").equals("true", ignoreCase = true)

val networkBuildConfigDir = layout.buildDirectory.dir("generated/networkBuildConfig")

val generateNetworkBuildConfig by tasks.registering {
    val outputDir = networkBuildConfigDir
    val url = supabaseUrl.toKotlinStringLiteralContent()
    val anonKey = supabaseAnonKey.toKotlinStringLiteralContent()
    val webClientId = googleWebClientId.toKotlinStringLiteralContent()
    val iosClientId = googleIosClientId.toKotlinStringLiteralContent()
    val loginEnabled = accountLoginEnabled
    // Without these, Gradle's up-to-date check only sees outputs.dir(outputDir) already exists —
    // it has no declared inputs to compare, so it never notices local.properties changed and
    // happily reports UP-TO-DATE while doLast's writeText silently never reruns. Real bug, caught
    // by actually testing ACCOUNT_LOGIN_ENABLED: commenting it back out in local.properties left
    // the generated file (and therefore the running app) still reading the old "true" value.
    inputs.property("supabaseUrl", url)
    inputs.property("supabaseAnonKey", anonKey)
    inputs.property("googleWebClientId", webClientId)
    inputs.property("googleIosClientId", iosClientId)
    inputs.property("accountLoginEnabled", loginEnabled)
    outputs.dir(outputDir)
    doLast {
        val packageDir = outputDir.get().dir("com/pamaz/vi/core/network/config").asFile
        packageDir.mkdirs()
        packageDir.resolve("NetworkBuildConfig.kt").writeText(
            """
            |// Generated by :core:network's build.gradle.kts (generateNetworkBuildConfig) — do not edit by hand.
            |// Values come from environment variables, falling back to the git-ignored root local.properties —
            |// never hardcoded, never committed. See SupabaseConfig's / GoogleAuthConfig's KDoc.
            |package com.pamaz.vi.core.network.config
            |
            |internal const val SUPABASE_URL: String = "$url"
            |internal const val SUPABASE_ANON_KEY: String = "$anonKey"
            |internal const val GOOGLE_WEB_CLIENT_ID: String = "$webClientId"
            |internal const val GOOGLE_IOS_CLIENT_ID: String = "$iosClientId"
            |internal const val ACCOUNT_LOGIN_ENABLED: Boolean = $loginEnabled
            |
            """.trimMargin()
        )
    }
}

